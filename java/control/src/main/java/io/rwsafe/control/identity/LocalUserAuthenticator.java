package io.rwsafe.control.identity;

import io.rwsafe.persistence.Database;
import io.rwsafe.persistence.LocalUser;
import java.util.Locale;
import java.util.Optional;
import java.util.Set;
import java.util.UUID;
import org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder;

/**
 * Local users created on the Administration screen (PO decision Q-47): the stored BCrypt hash is compared whether or not
 * the name exists and whether or not the user is enabled, so the answer takes as long either way and never says which
 * part was wrong. A disabled user is refused like a wrong password. A user whose password was generated by the control
 * plane signs in with {@link AuthenticatedUser#passwordChangeRequired()} set.
 */
public final class LocalUserAuthenticator implements Authenticator {

    public static final String SOURCE = "local_user";

    private final Database database;
    private final BCryptPasswordEncoder encoder = LocalUsers.ENCODER;
    private final String decoyHash = encoder.encode(UUID.randomUUID().toString());

    public LocalUserAuthenticator(Database database) {
        this.database = database;
    }

    @Override
    public Optional<AuthenticatedUser> authenticate(String loginName, char[] password) {
        String name = loginName.toLowerCase(Locale.ROOT);
        Optional<LocalUser> user = LocalUsers.LOGIN_NAME.matcher(name).matches()
            ? database.localUsers().find(name) : Optional.empty();
        String hash = user.filter(LocalUser::enabled).map(LocalUser::passwordHash).orElse(decoyHash);
        boolean matches = encoder.matches(new String(password), hash);
        if (!matches || user.isEmpty() || !user.get().enabled()) {
            return Optional.empty();
        }
        LocalUser u = user.get();
        return Optional.of(new AuthenticatedUser(u.loginName(), Set.copyOf(u.roles()), SOURCE, u.mustChangePassword()));
    }
}
