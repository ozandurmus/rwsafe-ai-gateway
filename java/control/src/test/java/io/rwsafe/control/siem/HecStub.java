package io.rwsafe.control.siem;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.MappingIterator;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.sun.net.httpserver.HttpExchange;
import com.sun.net.httpserver.HttpsConfigurator;
import com.sun.net.httpserver.HttpsServer;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.net.InetAddress;
import java.net.InetSocketAddress;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.ConcurrentLinkedQueue;
import java.util.concurrent.CopyOnWriteArrayList;
import java.util.concurrent.LinkedBlockingQueue;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicInteger;
import javax.net.ssl.SSLContext;

/**
 * A local Splunk HEC stand-in for the tests: HTTPS on a loopback port, {@code POST /services/collector/event}, the
 * {@code Authorization: Splunk <token>} header checked against a token generated by the test. Queued status codes are
 * answered first (to drive retries); then 200 with HEC's success body. Accepted events are parsed as concatenated JSON
 * objects.
 */
final class HecStub implements AutoCloseable {

    private static final ObjectMapper JSON = new ObjectMapper();
    private final HttpsServer server;
    private final String token;
    private final ConcurrentLinkedQueue<Integer> scripted = new ConcurrentLinkedQueue<>();
    private final LinkedBlockingQueue<JsonNode> events = new LinkedBlockingQueue<>();
    final List<String> paths = new CopyOnWriteArrayList<>();
    final AtomicInteger requests = new AtomicInteger();
    final AtomicInteger unauthorised = new AtomicInteger();

    HecStub(SSLContext context, String token) throws IOException {
        this.token = token;
        server = HttpsServer.create(new InetSocketAddress(InetAddress.getLoopbackAddress(), 0), 0);
        server.setHttpsConfigurator(new HttpsConfigurator(context));
        server.createContext("/", this::handle);
        server.start();
    }

    String url() {
        return "https://127.0.0.1:" + server.getAddress().getPort();
    }

    void answerNext(int... statuses) {
        for (int s : statuses) {
            scripted.add(s);
        }
    }

    List<JsonNode> take(int n, long millis) throws InterruptedException {
        List<JsonNode> out = new ArrayList<>();
        long deadline = System.currentTimeMillis() + millis;
        while (out.size() < n && System.currentTimeMillis() < deadline) {
            JsonNode e = events.poll(50, TimeUnit.MILLISECONDS);
            if (e != null) {
                out.add(e);
            }
        }
        return out;
    }

    private void handle(HttpExchange x) throws IOException {
        requests.incrementAndGet();
        paths.add(x.getRequestURI().getRawPath());
        byte[] body;
        try (InputStream in = x.getRequestBody()) {
            body = in.readAllBytes();
        }
        if (!("Splunk " + token).equals(x.getRequestHeaders().getFirst("Authorization"))) {
            unauthorised.incrementAndGet();
            respond(x, 401, "{\"text\":\"Invalid authorization\",\"code\":3}");
            return;
        }
        Integer status = scripted.poll();
        if (status != null) {
            respond(x, status, "{\"text\":\"scripted\",\"code\":9}");
            return;
        }
        try (MappingIterator<JsonNode> it = JSON.readerFor(JsonNode.class).readValues(body)) {
            while (it.hasNext()) {
                events.add(it.next());
            }
        }
        respond(x, 200, "{\"text\":\"Success\",\"code\":0}");
    }

    private static void respond(HttpExchange x, int status, String text) throws IOException {
        byte[] b = text.getBytes(StandardCharsets.UTF_8);
        x.sendResponseHeaders(status, b.length);
        try (OutputStream out = x.getResponseBody()) {
            out.write(b);
        }
    }

    @Override
    public void close() {
        server.stop(0);
    }
}
